print("/* neutrons in the most common (or most stable) isotope */")
print(arr("iso_n", "uint8_t", neu))
# pack state 2 bits per element, 4 per byte
packed = [0] * 30
for z in range(1, 119):
    packed[z // 4] |= st[z - 1] << (2 * (z % 4))
print("/* state at 25 C, 2 bits per element: 0 solid 1 liquid 2 gas 3 unknown */")
print("const uint8_t state_bits[30] = {" + ",".join(str(b) for b in packed) + "};")

# ionic radii (Shannon 1976, via mendeleev), pm x2: 6-coordinate, high spin,
# else the nearest coordination. Used to rank ions by bond strength.
ROMAN = {"I": 1, "II": 2, "III": 3, "IV": 4, "V": 5, "VI": 6, "VII": 7, "VIII": 8,
         "IX": 9, "X": 10, "XI": 11, "XII": 12, "XIV": 14}
def cn(s):
    for k in sorted(ROMAN, key=len, reverse=True):
        if s.startswith(k): return ROMAN[k]
    return 99
ions = []
for z in range(2, 119):
    best = {}
    for r in element(z).ionic_radii:
        if not r.ionic_radius or r.ionic_radius <= 0 or not -3 <= r.charge <= 8: continue
        key = (abs(cn(r.coordination) - 6), 0 if r.spin in ("HS", "") else 1, 0 if r.coordination[-1:] in "IVX" else 1)
        if r.charge not in best or key < best[r.charge][0]:
            best[r.charge] = (key, int(round(r.ionic_radius * 2)))
    for q in sorted(best):
        ions.append((z, q, best[q][1]))
print("/* ionic radius (Shannon, 6-coordinate where listed), half-pm: {Z, charge, r x2} */")
s = "const ion_r_t ion_radii[] = {"
for i, (z, q, r) in enumerate(ions):
    s += ("" if i % 8 else "\n    ") + f"{{{z},{q},{r}}},"
print(s.rstrip(",") + "};")
print("const uint8_t ion_radii_n = sizeof ion_radii / sizeof ion_radii[0];")
