"""Generate apps/ATOM/src/atomdata.c from the `mendeleev` package.
   pip install mendeleev && python3 tools/gen_atomdata.py > apps/ATOM/src/atomdata.c
Radii: empirical atomic radius (Slater) and covalent radius (Cordero), pm.
Isotope: most abundant natural isotope, else the mass number in data.c
(the longest-lived isotope)."""
import os, re
from mendeleev import element

# radioactive-only elements: use the mass number already in src/common/data.c
_data = open(os.path.join(os.path.dirname(__file__), "..", "src", "common", "data.c")).read()
DATA_MASS = {int(z): int(m) for m, z in re.findall(r'(\d+)UL, "[a-z]+", \{[^}]*\}\}, /\* (\d+) \*/', _data)}

# room-temperature state: 0 solid, 1 liquid, 2 gas, 3 unknown
GAS = {1, 2, 7, 8, 9, 10, 17, 18, 36, 54, 86}
LIQ = {35, 80}

emp, cov, neu, st = [], [], [], []
for z in range(1, 119):
    e = element(z)
    emp.append(int(round(e.atomic_radius or 0)))
    cov.append(int(round(e.covalent_radius_cordero or 0)))
    iso = [i for i in e.isotopes if i.abundance]
    if iso:
        best = max(iso, key=lambda i: i.abundance)
    else:
        best = None
    a = best.mass_number if best else round(DATA_MASS[z] / 1000)
    neu.append(a - z)
    st.append(2 if z in GAS else 1 if z in LIQ else 3 if z >= 104 else 0)

def arr(name, ctype, vals):
    s = f"const {ctype} {name}[NUM_ELEMENTS + 1] = {{0"
    for i, v in enumerate(vals):
        s += ("," if i % 16 else ",\n    ") + str(v)
    return s + "};\n"

print("/* atomdata.c - generated by tools/gen_atomdata.py (mendeleev). Index = Z. */")
print('#include "atom.h"\n')
print("/* empirical atomic radius, pm (0 = no data) */")
print(arr("rad_emp", "uint16_t", emp))
print("/* covalent radius (Cordero), pm (0 = no data) */")
print(arr("rad_cov", "uint16_t", cov))
print("/* neutrons in the most common (or most stable) isotope */")
print(arr("iso_n", "uint8_t", neu))
# pack state 2 bits per element, 4 per byte
packed = [0] * 30
for z in range(1, 119):
    packed[z // 4] |= st[z - 1] << (2 * (z % 4))
print("/* state at 25 C, 2 bits per element: 0 solid 1 liquid 2 gas 3 unknown */")
print("const uint8_t state_bits[30] = {" + ",".join(str(b) for b in packed) + "};")
